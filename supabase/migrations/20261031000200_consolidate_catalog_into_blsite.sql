-- Consolidated Blue Lock RP catalog schema for the owned blsite project.
-- Additive only: preserves all existing match/auth tables and data.
-- Catalog access remains server-mediated; RLS is enabled with no public policies.

create table if not exists public.characters (
  id integer generated by default as identity primary key,
  discord_id bigint not null unique,
  guild_id bigint not null,
  name text not null,
  character_name text not null default 'Игрок',
  shot_acc integer not null default 0,
  shot_power integer not null default 0,
  passing integer not null default 0,
  weak_foot integer not null default 0,
  dribble integer not null default 0,
  control integer not null default 0,
  header integer not null default 0,
  tackle integer not null default 0,
  steal integer not null default 0,
  strength integer not null default 0,
  jump integer not null default 0,
  stamina integer not null default 0,
  speed integer not null default 0,
  game_read integer not null default 0,
  vision integer not null default 0,
  points_train integer not null default 0,
  points_practice integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.teams (
  id integer generated by default as identity primary key,
  name text not null unique,
  owner_id bigint not null,
  vice_captain_id bigint,
  budget bigint not null default 1000000,
  created_at timestamptz not null default now()
);

create table if not exists public.team_players (
  id integer generated by default as identity primary key,
  discord_id bigint not null unique,
  team_id integer not null references public.teams(id),
  joined_at timestamptz not null default now()
);

create table if not exists public.transfers (
  id integer generated by default as identity primary key,
  player_id bigint not null,
  from_team_id integer references public.teams(id),
  to_team_id integer references public.teams(id),
  amount bigint not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.player_costs (
  id integer generated by default as identity primary key,
  discord_id bigint not null unique,
  cost bigint not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.offers (
  id integer generated by default as identity primary key,
  player_id bigint not null,
  seller_team_id integer not null references public.teams(id),
  buyer_team_id integer not null references public.teams(id),
  price bigint not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.career_stats (
  id integer generated by default as identity primary key,
  discord_id bigint not null unique,
  goals integer not null default 0,
  assists integer not null default 0,
  saves integer not null default 0,
  pushkas integer not null default 0,
  forward_of_season integer not null default 0,
  midfielder_of_season integer not null default 0,
  defender_of_season integer not null default 0,
  golden_glove integer not null default 0,
  league_cup integer not null default 0,
  mvp_season integer not null default 0,
  mvp_match integer not null default 0,
  goals_outside_box integer not null default 0,
  penalties_scored integer not null default 0,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists idx_team_players_team_id on public.team_players(team_id);
create index if not exists idx_transfers_from_team_id on public.transfers(from_team_id);
create index if not exists idx_transfers_to_team_id on public.transfers(to_team_id);
create index if not exists idx_offers_buyer_team_id on public.offers(buyer_team_id);
create index if not exists idx_offers_seller_team_id on public.offers(seller_team_id);
create index if not exists idx_characters_guild_id on public.characters(guild_id);

alter table public.characters enable row level security;
alter table public.teams enable row level security;
alter table public.team_players enable row level security;
alter table public.transfers enable row level security;
alter table public.player_costs enable row level security;
alter table public.offers enable row level security;
alter table public.career_stats enable row level security;

